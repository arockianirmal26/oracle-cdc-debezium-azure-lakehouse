-- Second business schema: BILLING, owned by a separate invoicing application.
--
-- A second schema in the same database, so multi-schema capture
-- (schema.include.list, or one Debezium instance per schema) can be tested.
--
-- Runs once as SYS when the database is first created.

ALTER SESSION SET CONTAINER = FREEPDB1;

-- Schema-only account: it owns tables but nobody can log in as BILLING.
-- That's how app schemas are often set up in practice. You work with the data
-- through SALES (grants below) or SYSTEM.
CREATE USER billing NO AUTHENTICATION QUOTA UNLIMITED ON users;

ALTER SESSION SET CURRENT_SCHEMA = BILLING;

-- One invoice per paid/shipped/delivered order. ORDER_ID points to SALES.ORDERS
-- but deliberately has no foreign key: separate apps rarely enforce
-- constraints across each other's schemas.
CREATE TABLE invoices (
    invoice_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no      VARCHAR2(20)  NOT NULL UNIQUE,
    order_id        NUMBER        NOT NULL,
    invoice_date    DATE          NOT NULL,
    due_date        DATE          NOT NULL,
    net_amount      NUMBER(12, 2) NOT NULL,
    vat_amount      NUMBER(12, 2) NOT NULL,
    gross_amount    NUMBER(12, 2) NOT NULL,
    payment_status  VARCHAR2(10)  NOT NULL
                    CHECK (payment_status IN ('OPEN', 'PAID', 'OVERDUE', 'REMINDED')),
    last_updated    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE OR REPLACE TRIGGER invoices_touch BEFORE UPDATE ON invoices
FOR EACH ROW BEGIN :new.last_updated := SYSTIMESTAMP; END;
/

CREATE INDEX invoices_order_ix ON invoices (order_id);

-- Seed from the existing orders. German VAT 19 % (order totals are treated as net).
-- Invoices older than 30 days are mostly paid; recent ones are mostly open.
INSERT INTO invoices (invoice_no, order_id, invoice_date, due_date, net_amount, vat_amount,
                      gross_amount, payment_status, last_updated)
SELECT 'RE-' || TO_CHAR(o.order_date, 'YYYY') || '-' || LPAD(o.order_id, 6, '0'),
       o.order_id,
       o.order_date + 1,
       o.order_date + 15,
       o.total_amount,
       ROUND(o.total_amount * 0.19, 2),
       ROUND(o.total_amount * 1.19, 2),
       CASE
           WHEN o.order_date > SYSDATE - 14 THEN 'OPEN'
           WHEN MOD(o.order_id, 50) = 0     THEN 'REMINDED'
           WHEN MOD(o.order_id, 23) = 0     THEN 'OVERDUE'
           WHEN o.order_date > SYSDATE - 30 THEN 'OPEN'
           ELSE 'PAID'
       END,
       CAST(o.order_date + 1 AS TIMESTAMP)
FROM sales.orders o
WHERE o.status IN ('PAID', 'SHIPPED', 'DELIVERED');

COMMIT;

-- Explicit invoice_ids weren't used, but keep the pattern consistent with SALES.
ALTER TABLE invoices MODIFY invoice_id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE);

-- Let the SALES login read and change invoices, so one DBeaver connection is
-- enough to work with both schemas (and to generate changes in both for CDC).
GRANT SELECT, INSERT, UPDATE, DELETE ON invoices TO sales;

EXEC DBMS_STATS.GATHER_SCHEMA_STATS('BILLING');
