-- Tables for a small order-management app, the kind of business application
-- typically found on Oracle. Runs once as SYS when the database is first created.
--
-- Two design choices matter for CDC:
--   * every table has a primary key  -> Debezium uses it as the event key
--   * every table has LAST_UPDATED   -> shows in the target when a row last changed

-- The image connects to the container database (FREE); our data lives in the
-- pluggable database FREEPDB1, in the SALES schema created via APP_USER.
ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = SALES;

-- Rows inserted by SYS still count against the table owner's quota.
ALTER USER sales QUOTA UNLIMITED ON users;

CREATE TABLE customers (
    customer_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_no   VARCHAR2(12)  NOT NULL UNIQUE,
    first_name    VARCHAR2(50),
    last_name     VARCHAR2(80)  NOT NULL,
    email         VARCHAR2(120),           -- nullable on purpose: real CRM data has gaps
    city          VARCHAR2(60),
    country_code  CHAR(2)       DEFAULT 'DE' NOT NULL,
    created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    last_updated  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE orders (
    order_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   NUMBER        NOT NULL REFERENCES customers (customer_id),
    order_date    DATE          NOT NULL,
    status        VARCHAR2(12)  NOT NULL
                  CHECK (status IN ('NEW', 'PAID', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    total_amount  NUMBER(12, 2) NOT NULL,
    currency      CHAR(3)       DEFAULT 'EUR' NOT NULL,
    last_updated  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE order_items (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      NUMBER        NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    product_sku   VARCHAR2(20)  NOT NULL,
    quantity      NUMBER(5)     NOT NULL,
    unit_price    NUMBER(10, 2) NOT NULL,
    last_updated  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

-- Many apps forget to maintain LAST_UPDATED; here a trigger guarantees it on every UPDATE.
CREATE OR REPLACE TRIGGER customers_touch BEFORE UPDATE ON customers
FOR EACH ROW BEGIN :new.last_updated := SYSTIMESTAMP; END;
/
CREATE OR REPLACE TRIGGER orders_touch BEFORE UPDATE ON orders
FOR EACH ROW BEGIN :new.last_updated := SYSTIMESTAMP; END;
/
CREATE OR REPLACE TRIGGER order_items_touch BEFORE UPDATE ON order_items
FOR EACH ROW BEGIN :new.last_updated := SYSTIMESTAMP; END;
/

-- Queries by change time filter on LAST_UPDATED, so index it.
CREATE INDEX orders_last_updated_ix ON orders (last_updated);
CREATE INDEX order_items_order_ix   ON order_items (order_id);
